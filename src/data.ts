export function getInspiredByShort(id: string, language?: string): string {
  let text = inspiredByMap[id] || "Inspired by Signature";
  if (language === "is") {
    text = text.replace("Inspired by", "Ilmar eins og");
  } else if (language === "es") {
    text = text.replace("Inspired by", "Inspirado en");
  }
  return text;
}

